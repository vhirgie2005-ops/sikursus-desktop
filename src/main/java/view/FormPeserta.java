    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        String nim = txtNim.getText().trim();
String nama = txtNama.getText().trim();
String prodi = txtProdi.getText().trim();
String noHp = txtNoHp.getText().trim();
String email = txtEmail.getText().trim();

String jenisKelamin = "";
if (rbLaki.isSelected()) {
    jenisKelamin = "L";
} else if (rbPerempuan.isSelected()) {
    jenisKelamin = "P";
}

if (nim.isEmpty() || nama.isEmpty() || prodi.isEmpty()
        || jenisKelamin.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "NIM, nama, jenis kelamin, dan prodi wajib diisi.",
            "Validasi",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}

model.Peserta peserta = new model.Peserta(
        nim, nama, jenisKelamin, prodi, noHp, email
);

try {
    dao.PesertaDAO pesertaDAO = new dao.PesertaDAO();

    if (pesertaDAO.insert(peserta)) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Data peserta berhasil disimpan."
        );

        txtNim.setText("");
        txtNama.setText("");
        buttonGroupJenisKelamin.clearSelection();
        txtProdi.setText("");
        txtNoHp.setText("");
        txtEmail.setText("");
        txtNim.requestFocusInWindow();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Data tidak tersimpan."
        );
    }
} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Gagal menyimpan data:\n" + e.getMessage(),
            "Database Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
    );
    e.printStackTrace();
}
    }//GEN-LAST:event_btnSimpanActionPerformed

